/* ── Chat Panel ── */
function ChatPanel({ agent, inputs }: { agent: AgentConfig | null; inputs: Record<string, string> }) {
  const [messages, setMessages] = useState<ChatMessage[]>([
    { role: "agent", content: "👋 Hello! I'm your agent. Send me a message and I'll process it according to my configuration." },
  ]);
  const [input, setInput] = useState("");
  const [isTyping, setIsTyping] = useState(false);
  const [apiMode, setApiMode] = useState<"simulated" | "live">("simulated");
  const chatEndRef = useRef<HTMLDivElement>(null);

  // Check if API keys are available — re-check whenever Settings opens or closes
  useEffect(() => {
    const checkKeys = () => {
      const { openai, gemini } = getApiKeys();
      setApiMode(openai || gemini ? "live" : "simulated");
    };
    checkKeys();
    window.addEventListener("open-settings", checkKeys);
    window.addEventListener("clawless-settings-closed", checkKeys);
    return () => {
      window.removeEventListener("open-settings", checkKeys);
      window.removeEventListener("clawless-settings-closed", checkKeys);
    };
  }, []);

  useEffect(() => {
    chatEndRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, isTyping]);

  const handleSend = useCallback(async () => {
    if (!input.trim() || !agent) return;

    const userMsg = input.trim();
    setInput("");
    setMessages((prev) => [...prev, { role: "user", content: userMsg }]);

    setIsTyping(true);
    try {
      let response: string;
      let simulated = false;

      if (apiMode === "live") {
        const llmMessages = [
          { role: "system" as const, content: agent.persona.systemPrompt },
          { role: "user" as const, content: `Input values: ${JSON.stringify(inputs)}\n\nUser message: ${userMsg}` },
        ];
        const result = await callLLM(llmMessages);
        if (result && result.trim()) {
          response = result;
        } else {
          // Provider returned nothing — surface it instead of quietly faking a reply
          response = "⚠️ The AI provider returned an empty response. No output was generated — please try again, or check your API key in Settings.";
        }
      } else {
        // Simulate a delay for realism
        await new Promise((resolve) => setTimeout(resolve, 1200 + Math.random() * 800));
        response = simulateAgentResponse(agent.persona.systemPrompt, userMsg, inputs);
        simulated = true;
      }

      setMessages((prev) => [...prev, { role: "agent", content: response, simulated }]);
    } catch (err) {
      const errorMsg = err instanceof Error ? err.message : "Unknown error";
      setMessages((prev) => [...prev, { role: "agent", content: `⚠️ Error: ${errorMsg}\n\nFalling back to simulation...` }]);
      // Fallback to simulation — tagged so the bubble carries the Simulated marker
      const fallback = simulateAgentResponse(agent.persona.systemPrompt, userMsg, inputs);
      setMessages((prev) => [...prev, { role: "agent", content: fallback, simulated: true }]);
    } finally {
      setIsTyping(false);
    }
  }, [input, agent, inputs, apiMode]);

  return (
    <div className="flex flex-col h-full">
      {/* Chat header */}
      <div className="flex items-center gap-2 px-4 py-3 border-b border-gray-800">
        <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-violet-600/15 text-lg">
          {agent?.persona.icon || "🤖"}
        </div>
        <div className="flex-1">
          <div className="text-sm font-medium text-gray-200">{agent?.persona.name || "Agent Chat"}</div>
          <div className="flex items-center gap-1.5">
            <span className="text-xs text-gray-500">Test your agent in real-time</span>
            <span className={`inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-[10px] font-medium ${
              apiMode === "live"
                ? "bg-emerald-600/15 text-emerald-400 border border-emerald-600/30"
                : "bg-amber-600/15 text-amber-400 border border-amber-600/30"
            }`}>
              <span className={`inline-block w-1.5 h-1.5 rounded-full ${apiMode === "live" ? "bg-emerald-400" : "bg-amber-400"}`} />
              {apiMode === "live" ? "Live" : "Simulated"}
            </span>
          </div>
        </div>
      </div>

      {/* Messages */}
      <div className="flex-1 overflow-y-auto px-4 py-4 space-y-4">
        {messages.map((msg, i) => (
          <div key={i} className={`flex ${msg.role === "user" ? "justify-end" : "justify-start"} animate-fade-in`}>
            <div
              className={`max-w-[85%] rounded-2xl px-4 py-3 text-sm leading-relaxed ${
                msg.role === "user"
                  ? "bg-violet-600/20 text-gray-200 border border-violet-600/20"
                  : "bg-gray-800/60 text-gray-300 border border-gray-700/50"
              }`}
            >
              {msg.simulated && (
                <span className="mb-1.5 inline-flex items-center gap-1 rounded-full border border-amber-600/30 bg-amber-600/15 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-amber-400">
                  <span className="inline-block h-1.5 w-1.5 rounded-full bg-amber-400" />
                  Simulated
                </span>
              )}
              <div className="whitespace-pre-wrap">{msg.content}</div>
            </div>
          </div>
        ))}
        {isTyping && (
          <div className="flex justify-start animate-fade-in">
            <div className="bg-gray-800/60 border border-gray-700/50 rounded-2xl px-4 py-3">
              <div className="flex items-center gap-1.5">
                <span className="typing-dot inline-block w-2 h-2 rounded-full bg-violet-400" />
                <span className="typing-dot inline-block w-2 h-2 rounded-full bg-violet-400" />
                <span className="typing-dot inline-block w-2 h-2 rounded-full bg-violet-400" />
              </div>
            </div>
          </div>
        )}
        <div ref={chatEndRef} />
      </div>

      {/* Input */}
      <div className="border-t border-gray-800 px-4 py-3">
        <div className="flex items-center gap-2">
          <input
            type="text"
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === "Enter" && !e.shiftKey) {
                e.preventDefault();
                handleSend();
              }
            }}
            placeholder="Type a message to test your agent..."
            className="flex-1 rounded-lg border border-gray-700 bg-gray-900 px-3.5 py-2.5 text-sm text-gray-200 placeholder-gray-500 focus:outline-none focus:ring-2 focus:ring-violet-600/50 focus:border-violet-600/50 transition-all"
          />
          <button
            onClick={handleSend}
            disabled={!input.trim() || !agent}
            className="flex h-10 w-10 items-center justify-center rounded-lg bg-violet-600 text-white hover:bg-violet-500 disabled:opacity-40 disabled:cursor-not-allowed transition-all"
          >
            <Send className="h-4 w-4" />
          </button>
        </div>
      </div>
    </div>
  );
}

