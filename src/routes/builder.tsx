/* ── Real LLM API Functions ── */
async function callOpenAI(messages: { role: string; content: string }[], apiKey: string, jsonMode = false): Promise<string> {
  const response = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${apiKey}`,
    },
    body: JSON.stringify({
      model: "gpt-4o-mini",
      messages,
      max_tokens: 1024,
      temperature: 0.7,
      ...(jsonMode ? { response_format: { type: "json_object" } } : {}),
    }),
  });

  if (!response.ok) {
    const err = await response.text();
    throw new Error(`OpenAI API error (${response.status}): ${err}`);
  }

  const data = await response.json();
  return data.choices[0]?.message?.content || "No response generated.";
}

async function callGemini(systemPrompt: string, userMessage: string, apiKey: string, jsonMode = false): Promise<string> {
  const response = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key=${apiKey}`,
    {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        contents: [
          {
            role: "user",
            parts: [{ text: `${systemPrompt}\n\nUser: ${userMessage}` }],
          },
        ],
        generationConfig: {
          maxOutputTokens: 1024,
          temperature: 0.7,
          ...(jsonMode ? { responseMimeType: "application/json" } : {}),
        },
      }),
    },
  );

  if (!response.ok) {
    const err = await response.text();
    throw new Error(`Gemini API error (${response.status}): ${err}`);
  }

  const data = await response.json();
  return data.candidates?.[0]?.content?.parts?.[0]?.text || "No response generated.";
}

function getApiKeys(): { openai: string; gemini: string } {
  if (typeof window === "undefined") return { openai: "", gemini: "" };
  return {
    openai: localStorage.getItem("clawless_openai_key") || localStorage.getItem("agentforge_openai_key") || "",
    gemini: localStorage.getItem("clawless_gemini_key") || localStorage.getItem("agentforge_gemini_key") || "",
  };
}

async function callLLM(messages: { role: string; content: string }[], jsonMode = false): Promise<string | null> {
  const { openai, gemini } = getApiKeys();

  if (openai) {
    return callOpenAI(messages, openai, jsonMode);
  }
  if (gemini) {
    const systemMsg = messages.find((m) => m.role === "system")?.content || "";
    const userMsg = messages.filter((m) => m.role === "user").map((m) => m.content).join("\n");
    return callGemini(systemMsg, userMsg, gemini, jsonMode);
  }

  return null; // No API key available
}

/* ── Simulated LLM Engine ── */
function simulateAgentResponse(systemPrompt: string, userInput: string, inputs: Record<string, string>): string {
  const inputContext = Object.entries(inputs).map(([k, v]) => `${k}: ${v}`).join(", ");

  const responses: string[] = [
    `SIMULATED PREVIEW — no real work was performed.\n\nThis is a format preview of how this agent would respond once connected to a live AI provider.\n\nRequest: "${userInput}"\n${inputContext ? `Sample context: ${inputContext}\n` : ""}\nExpected output shape:\n• Summary: [agent's summary would appear here]\n• Details: [key points generated by the live model]\n\nNothing was actually processed, sent, or saved. Add your own API key in Settings to run this agent for real.`,
    `SIMULATED PREVIEW — no real work was performed.\n\nRequest: "${userInput}"\n\nThis agent is not connected to a live AI provider yet, so here is the response format it would produce:\n\n---\n[Agent name]: ${systemPrompt.split("\n")[0] || "Your agent"}\nInput: ${userInput}\nOutput: [live-generated response would appear here]\n---\n\nThis is a placeholder showing output structure only. Connect your own API key in Settings to generate a real response.`,
    `SIMULATED PREVIEW — no real work was performed.\n\nHere is what the final output of this agent will look like:\n\n\`\`\`\nStatus: Preview (no AI provider connected)\nInput: ${userInput}\nOutput: [generated content would appear here]\n\`\`\`\n\nThis demonstrates the output format only — no task was executed and no data was produced. Add your own API key in Settings to run this agent live.`,
  ];

  return responses[Math.floor(Math.random() * responses.length)];
}

